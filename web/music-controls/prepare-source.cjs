'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {MUSIC_PLAYER_CONTROLS_FACTORY_SOURCE} = require('../../desktop/native/music-player-controls-runtime.cjs');

function prepareSource(checkout) {
  const directory = path.join(checkout, 'fluxer_app/src/features/channel/components');
  const file = path.join(directory, 'MessageAttachments.tsx');
  const input = fs.readFileSync(file, 'utf8');
  const importLine = "import {MusicPlayerControls} from '@app/features/channel/components/MusicPlayerControls';\n";
  const child = '\t\t\t{UserSettings.renderEmbeds && !message.suppressEmbeds && (\n' +
    '\t\t\t\t<MusicPlayerControls message={message} channel={channel} isPreview={reactionsIsPreview} />\n\t\t\t)}\n';
  let output = input;
  if (!output.includes(importLine.trim())) {
    const anchor = "import {MessageReactions} from '@app/features/channel/components/MessageReactions';";
    assert.equal(output.split(anchor).length, 2, 'Unexpected message imports');
    output = output.replace(anchor, anchor + '\n' + importLine.trimEnd());
  }
  if (!output.includes('<MusicPlayerControls message={message}')) {
    const anchor = '\t\t\t{UserSettings.renderReactions && reactions.length > 0 && (';
    assert.equal(output.split(anchor).length, 2, 'Unexpected reaction render boundary');
    output = output.replace(anchor, child + anchor);
  }
  const component = `// SPDX-License-Identifier: AGPL-3.0-or-later
// @ts-nocheck -- Shared, tested runtime generated by DxD/web/music-controls/prepare-source.cjs.
import React from 'react';
import {jsx, jsxs} from 'react/jsx-runtime';
import {useLingui} from '@lingui/react';
import {Button} from '@app/features/ui/button/Button';
import {http} from '@app/features/platform/transport/RestTransport';
export const MusicPlayerControls = ${MUSIC_PLAYER_CONTROLS_FACTORY_SOURCE}({
  React, jsx, jsxs, Button, http, getLocale: () => useLingui().i18n.locale,
});
`;
  fs.writeFileSync(file, output);
  fs.writeFileSync(path.join(directory, 'MusicPlayerControls.tsx'), component);
  return {changed: input !== output, componentBytes: Buffer.byteLength(component)};
}
module.exports = {prepareSource};
if (require.main === module) {
  assert.ok(process.argv[2], 'Pass the Fluxer source checkout');
  console.log(JSON.stringify(prepareSource(path.resolve(process.argv[2]))));
}
